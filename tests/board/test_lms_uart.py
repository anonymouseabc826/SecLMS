def sec_wrapped_read(port: serial.Serial) -> bytes:
    """Fetch the 48B wrapped blob: LO=28B (blob[0..27]) + HI=20B (blob[28..47]),
    response body is capped at 28B (same accounting as NVM_READ)."""
    blob = bytearray(48)
    r = sec_cmd(port, SEC_SUB_WRAPPED_READ_LO)
    if r[18] != 0:
        raise RuntimeError(f"wrapped_read_lo: status={r[18]}")
    for i in range(28):
        blob[i] = r[20 + i]
    r = sec_cmd(port, SEC_SUB_WRAPPED_READ_HI)
    if r[18] != 0:
        raise RuntimeError(f"wrapped_read_hi: status={r[18]}")
    for i in range(20):
        blob[28 + i] = r[20 + i]
    return bytes(blob)


def sec_wrap_load(port: serial.Serial, blob: bytes) -> None:
    if len(blob) != 48:
        raise RuntimeError("sec_wrap_load: blob needs 48B")
    r = sec_cmd(port, SEC_SUB_WRAP_LOAD, blob)
    if r[18] != 0:
        raise RuntimeError(f"sec_wrap_load: status={r[18]}")


def nvm_read_full64(port: serial.Serial) -> bytes:
    """Three parameterless READs fetch the full 64B of the active slot (including tag)."""
    rec = bytearray(64)
    for op, base in ((0x03, 0), (0x05, 28), (0x04, 36)):
        write_paced(port, bytes((REQUEST_NVM_SYNC, op)))
        r = read_exact(port, RESPONSE_SIZE)
        if r[18] != 0 or r[19] != 3:
            raise RuntimeError(f"nvm_read64: op={op} status={r[18]} mask={r[19]}")
        for i in range(28):
            if base + i < 64:
                rec[base + i] = r[20 + i]
    return bytes(rec)


def sec_sign(port: serial.Serial, vector: dict[str, str]) -> tuple[int, int, bytes, int, int, int]:
    """SEC_SIGN atomic signature, return (status, q_out, signature, sign_rc, hw_cycles, total_cycles).
    sign_rc = specific lmots_sign error code (diagnostic, firmware nvm_response[3] -> response frame[19]).
    hw_cycles = frame[4..7] (hardware derive+sign compressed ticks); total_cycles = frame[20..23]
    (end-to-end SOC_CYCLE_COUNT delta, same offset as normal commands).
    Types are read from the vector private key per parameter set (lms_private_key: lms_type(4)||lmots_type(4)||I(16)||
    seed(32)||q(4), big-endian), signature length derived from vector LMOTS_SIGNATURE (all w supported).
    Single-key fixed scheme: no key_handle field (SEC-slot SEED loaded by provisioning)."""
    priv = bytes.fromhex(vector["PRIVATE_KEY"])
    message = bytes.fromhex(vector["MESSAGE"])
    i_field = priv[8:24]
    lms_type = int.from_bytes(priv[0:4], "big")
    lmots_type = int.from_bytes(priv[4:8], "big")
    request = bytearray((REQUEST_SEC_SIGN,))
    request += i_field
    request += struct.pack("<I", lms_type)
    request += struct.pack("<I", lmots_type)
    request += struct.pack(">H", len(message)) + message
    write_paced(port, bytes(request))
    response = read_exact(port, RESPONSE_SIZE)
    if response[0] != RESPONSE:
        raise RuntimeError(f"sec_sign: marker=0x{response[0]:02x}")
    status = response[18]
    # sign_rc (specific lmots_sign code) is placed by firmware in nvm_response[3] -> serve_uart sends it in response frame [19]
    sign_rc = response[19]
    q_out = struct.unpack_from(">I", response, 36)[0]
    hw_cycles = struct.unpack_from("<I", response, 4)[0]
    total_cycles = struct.unpack_from("<I", response, 20)[0]
    signature = b""
    if response[1] == 0 and status == 0:
        signature = read_exact(port, len(bytes.fromhex(vector["LMOTS_SIGNATURE"])))
    return status, q_out, signature, sign_rc, hw_cycles, total_cycles


def gen_sec_expected_sig(q: int, vector: dict[str, str]) -> bytes:
    """Use the PC generator to produce the expected LM-OTS signature for q (SEC_SIGN signature = lmots_sign(q, vector message),
    consistent with the Verilator secsign-1 comparison logic). The generator uses fixed I/seed, same source as the vector."""
    priv = bytes.fromhex(vector["PRIVATE_KEY"])
    lms_type = int.from_bytes(priv[0:4], "big")
    lmots_type = int.from_bytes(priv[4:8], "big")
    out = subprocess.run(
        ["build/generate_lms_verify_vector.exe", f"--lms={lms_type}",
         f"--lmots={lmots_type}", f"--q={q}"],
        capture_output=True, text=True, cwd=str(Path(__file__).resolve().parents[2]),
    ).stdout
    m = re.search(r"LMOTS_SIGNATURE=([0-9a-fA-F]+)", out)
    if not m:
        raise RuntimeError(f"gen_sec_expected_sig: generator failed for q={q}")
    return bytes.fromhex(m.group(1))


