def _hash(data: bytes) -> bytes:
    """32B digest oracle for the hash under test (matches on-board HASH_ONCE/CHAIN semantics)."""
    if HASH_MODE == "shake256":
        return hashlib.shake_256(data).digest(32)
    return hashlib.sha256(data).digest()


def _chain_expected(identifier: bytes, q: int, index: int, start: int, steps: int, value: bytes) -> bytes:
    """CHAIN chained-iteration oracle (I||u32str(q)||u16str(i)||u8str(j)||chain)."""
    expected = value
    for chain_index in range(start, start + steps):
        expected = _hash(
            identifier
            + q.to_bytes(4, "big")
            + index.to_bytes(2, "big")
            + bytes((chain_index,))
            + expected
        )
    return expected

