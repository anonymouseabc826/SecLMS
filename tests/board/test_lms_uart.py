def run_deploy_board_cases(port: serial.Serial, vector: dict[str, str]) -> None:
    """P1-6 (0.1.274) deploy two-phase part B (deploy bit, INSECURE_TEST_MODE=0 + SEC_TEST=0):
    plaintext SEED_LOAD/FACTORY_INIT/INJECT_TAG rejected -> wrapped push-back -> BOOT unwrap restores SEED
    (plaintext never stored) -> 0x67/0x66/0x56 self-consistent closed loop (device-specific public key, correctness endorsed by signature verification)."""
    blob = Path("build/deploy_blob.bin").read_bytes()
    if len(blob) != 48:
        raise RuntimeError("build/deploy_blob.bin missing (run --deploy-factory phase A first)")

    # (1) Plaintext SEED_LOAD (0x63) rejected: frame[1]=1, frame[2]=RTL ERR_INSECURE_DISABLED=0x0a.
    write_paced(port, bytes((0x63,)) + b"\x21" * 32)
    r = read_exact(port, RESPONSE_SIZE)
    if r[1] != 1 or r[2] != 0x0A:
        raise RuntimeError(f"deploy seed-load: status={r[1]} hw_error=0x{r[2]:02x} (expect 1/0x0a)")
    print("PASS: deploy seed-load rejected hw_error=0x0a (plaintext SEED closed)")

    # (2) FACTORY_INIT / INJECT_TAG rejected (deploy firmware SEC_ERR_UNSUPPORTED=9).
    r = sec_cmd(port, SEC_SUB_FACTORY_INIT, _key_i(vector))
    if r[18] != 9:
        raise RuntimeError(f"deploy factory-init: status={r[18]} (expect 9)")
    print("PASS: deploy factory-init rejected status=9 (factory config only)")
    r = sec_cmd(port, SEC_SUB_INJECT_TAG)
    if r[18] != 9:
        raise RuntimeError(f"deploy inject-tag: status={r[18]} (expect 9)")
    print("PASS: deploy inject-tag rejected status=9")

    # (3) wrapped push-back -> BOOT -> IDLE ctr=0 (unwrap restores SEED, plaintext never stored).
    sec_wrap_load(port, blob)
    state, ctr = sec_boot(port, _key_i(vector))
    if state != 1 or ctr != 0:
        raise RuntimeError(f"deploy boot: state={state} ctr={ctr} (expect IDLE/0)")
    print("PASS: deploy boot unwrap OK state=IDLE ctr=0 key_loaded=1")

    # (4) 0x67 KeyGen -> device-specific public key; 0x66 Sign x2 -> q=0/1, ctr increasing; 0x56 self-consistent verification.
    status, pub, _, _ = sec_lms_keygen(port, vector)
    if status != 0:
        raise RuntimeError(f"deploy keygen: status={status}")
    print("PASS: deploy sec-lms-keygen pub produced (device-specific)")
    # Device KeyGen-generated I = public key [8:24] (PK=lmstype(4)||otstype(4)||I(16)||T1(32)),
    # sign request uses this device I (host records the public key to obtain I and sends it back for sign - consistent with keygen, not the vector I).
    device_i = pub[8:24]

    status, q0, sig0, _, _, _ = sec_lms_sign(port, vector, i_override=device_i)
    if status != 0 or q0 != 0:
        raise RuntimeError(f"deploy sign-1: status={status} q={q0}")
    _, ctr1, _ = sec_get_state(port)
    if ctr1 != 1:
        raise RuntimeError(f"deploy sign-1 post ctr={ctr1} (expect 1)")
    print("PASS: deploy sec-lms-sign-1 q=0 committed ctr=1 (Release=>Committed)")

    status, q1, _, _, _, _ = sec_lms_sign(port, vector, i_override=device_i)
    if status != 0 or q1 != 1:
        raise RuntimeError(f"deploy sign-2: status={status} q={q1}")
    print("PASS: deploy sec-lms-sign-2 q=1 strictly increasing")

    msg = bytes.fromhex(vector["MESSAGE"])
    verify_request = bytes((REQUEST_VERIFY,)) + pub + struct.pack(">H", len(msg)) + msg + sig0
    original_timeout = port.timeout
    try:
        port.timeout = 60.0
        write_paced(port, verify_request, chunk_size=4, sleep_time=0.004)
        rv = read_exact(port, RESPONSE_SIZE)
    finally:
        port.timeout = original_timeout
    if rv[1] != 0:
        raise RuntimeError(f"deploy verify: status={rv[1]} hex={rv[:8].hex()}")
    print("PASS: deploy verify self-consistent (0x67 pub x 0x66 sig)")

    # (5) (0.1.281 model B) 0x68 KEYGEN_NEW (deploy): new SEED+I generated on the fly by the **on-device TRNG**
    # (CMD_SEED_WRITE_SAFE controlled load into slot 0, plaintext SEED_LOAD gating remains) -> pubB!=pubA, ctr reset
    # -> Sign q=0 (new device I) -> Verify self-consistent (full multi-key-rotation deploy chain; host should persist the new blob).
    dummy_i = b"\x00" * 16   # deploy ignores i_new (device generates I)
    status, pub_b, _, _ = sec_lms_keygen_new(port, vector, dummy_i)
    if status != 0:
        raise RuntimeError(f"deploy keygen-new: status={status}")
    if pub_b == pub or len(pub_b) != len(pub):
        raise RuntimeError("deploy keygen-new: pubB == pubA (expected fresh on-device key)")
    print("PASS: deploy keygen-new status=0 pubB != pubA (on-device TRNG SEED+I)")
    _, ctr_b, _ = sec_get_state(port)
    if ctr_b != 0:
        raise RuntimeError(f"deploy keygen-new post ctr={ctr_b} (expect 0, fresh key)")
    print("PASS: deploy keygen-new post-rotate ctr=0 (fresh q)")
    status, qb0, sig_b, _, _, _ = sec_lms_sign(port, vector, i_override=pub_b[8:24])
    if status != 0 or qb0 != 0:
        raise RuntimeError(f"deploy keygen-new sign: status={status} q={qb0}")
    verify_request_b = bytes((REQUEST_VERIFY,)) + pub_b + struct.pack(">H", len(msg)) + msg + sig_b
    try:
        port.timeout = 60.0
        write_paced(port, verify_request_b, chunk_size=4, sleep_time=0.004)
        rvb = read_exact(port, RESPONSE_SIZE)
    finally:
        port.timeout = original_timeout
    if rvb[1] != 0:
        raise RuntimeError(f"deploy keygen-new verify: status={rvb[1]} hex={rvb[:8].hex()}")
    print("PASS: deploy keygen-new verify self-consistent (fresh key full chain)")
    print("PASS: board deploy-semantics closed loop (rejections + BOOT unwrap + 0x67/0x66/0x56 + 0x68 multi-key-rotation self-consistent)")


def read_exact(port: serial.Serial, size: int) -> bytes:
    data = bytearray()
    while len(data) < size:
        chunk = port.read(size - len(data))
        if not chunk:
            raise TimeoutError(f"UART timeout after {len(data)}/{size} response bytes")
        data.extend(chunk)
    return bytes(data)


def write_paced(
    port: serial.Serial, data: bytes, chunk_size: int = 16, sleep_time: float = 0.001
) -> None:
    for offset in range(0, len(data), chunk_size):
        port.write(data[offset : offset + chunk_size])
        port.flush()
        time.sleep(sleep_time)


def run_case(
    port: serial.Serial,
    name: str,
    message: bytes,
    expected_cycles: int,
    previous_hits: int | None,
) -> int:
    port.write(bytes((REQUEST_HASH, len(message))) + message)
    port.flush()
    response = read_exact(port, RESPONSE_SIZE)
    marker, status, hw_error, reserved, cycles, hits, fallback = struct.unpack_from("<BBBBIII", response)
    digest = response[16:48]
    expected_digest = _hash(message)

    if marker != RESPONSE or status != 0 or hw_error != 0 or reserved != 0:
        raise RuntimeError(
            f"{name}: marker=0x{marker:02x} status={status} hw_error={hw_error} reserved={reserved}"
        )
    hits_valid = hits >= 2 if previous_hits is None else hits == previous_hits + 1
    if cycles != expected_cycles or not hits_valid or fallback != 0:
        raise RuntimeError(
            f"{name}: cycles={cycles}/{expected_cycles} hits={hits} "
            f"previous_hits={previous_hits} fallback={fallback}"
        )
    if digest != expected_digest:
        raise RuntimeError(f"{name}: digest={digest.hex()} expected={expected_digest.hex()}")

    print(
        f"PASS: {name:<6} bytes={len(message):3d} cycles={cycles} "
        f"hits={hits} fallback={fallback} digest={digest.hex()}"
    )
    return hits


