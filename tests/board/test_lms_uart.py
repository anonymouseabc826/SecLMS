def sec_commit(port: serial.Serial, new_state: int, ctr: int, reserved_q: int) -> tuple[int, int]:
    """CMD COMMIT, return (status, tx)."""
    params = struct.pack(">III", new_state, ctr, reserved_q)
    r = sec_cmd(port, SEC_SUB_COMMIT, params)
    return r[18], struct.unpack_from(">I", r, 20)[0]


