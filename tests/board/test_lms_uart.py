def sec_lms_sign(port: serial.Serial, vector: dict[str, str],
                 timeout: float = 60.0,
                 i_override: bytes = b"") -> tuple[int, int, bytes, int, int, int]:
    """SEC_LMS_SIGN (0x66): secured full LMS signature (sec_sign state machine + auth path).
    Return (status, q, signature, hw_cycles, total_cycles, steady_total).
    Request: I(16)||lms_type(4)||lmots_type(4)||msg_len(2,BE)||message (single-key fixed scheme
    has no key_handle).
    i_override: when non-empty use these 16B as I (device I=pub[8:24] from the device KeyGen-produced public key, for deploy
    self-consistency); when empty use the vector I (priv[8:24]).
    Response: frame[4..7]=hw; [16..19]=q; [20..23]=total; [24..27]=steady. Signature follows."""
    priv = bytes.fromhex(vector["PRIVATE_KEY"])
    message = bytes.fromhex(vector["MESSAGE"])
    i_field = i_override if len(i_override) == 16 else priv[8:24]
    lms_type = int.from_bytes(priv[0:4], "big")
    lmots_type = int.from_bytes(priv[4:8], "big")
    request = bytearray((REQUEST_SEC_LMS_SIGN,))
    request += i_field
    request += struct.pack("<I", lms_type)
    request += struct.pack("<I", lmots_type)
    request += struct.pack(">H", len(message)) + message
    original_timeout = port.timeout
    try:
        port.timeout = timeout
        write_paced(port, bytes(request))
        response = read_exact(port, RESPONSE_SIZE)
    finally:
        port.timeout = original_timeout
    if response[0] != RESPONSE:
        raise RuntimeError(f"sec_lms_sign: marker=0x{response[0]:02x}")
    status = response[1]
    q = struct.unpack_from("<I", response, 16)[0]
    hw = struct.unpack_from("<I", response, 4)[0]
    total = struct.unpack_from("<I", response, 20)[0]
    steady = struct.unpack_from("<I", response, 24)[0]
    signature = b""
    if status == 0:
        signature = read_exact(port, len(bytes.fromhex(vector["SIGNATURE"])))
    return status, q, signature, hw, total, steady


