REQUEST_NVM_SYNC = 0x52
NVM_SUB_PUSH_LO = 0x01
NVM_SUB_PUSH_HI = 0x02
NVM_SUB_READ = 0x03
NVM_STATE_LEN = 64
NVM_CHUNK_LEN = 32
NVM_STORE_FILE = Path("build/nvm_state.bin")


def crc16_ccitt(data: bytes) -> int:
    """CRC16-CCITT(0xFFFF), matching the firmware nvm_sync."""
    crc = 0xFFFF
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


class NvmStore:
    """Host persistent domain: file mirror of the 64B STATE_REC + push-back/read-back/corruption injection.

    The firmware NVM slot is volatile (cleared on reset); power-off persistence is handled by the host file this class maintains.
    After power-up the runner pushes the file contents back to the firmware via PUSH_LO/HI; firmware NVM_SYNC READ can verify it."""

    def __init__(self, path: Path = NVM_STORE_FILE) -> None:
        self.path = path

    def load(self) -> bytes:
        if not self.path.exists():
            return bytes(NVM_STATE_LEN)
        data = self.path.read_bytes()
        if len(data) != NVM_STATE_LEN:
            raise RuntimeError(f"NvmStore: {self.path} length {len(data)} != {NVM_STATE_LEN}")
        return data

    def save(self, state: bytes) -> None:
        if len(state) != NVM_STATE_LEN:
            raise RuntimeError(f"NvmStore: state length {len(state)} != {NVM_STATE_LEN}")
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_bytes(state)

    def clear(self) -> None:
        if self.path.exists():
            self.path.unlink()

    def corrupt(self, offset: int, value: int) -> None:
        """Inject corruption: overwrite one byte of the persistent domain (tests firmware rejection of a corrupt STATE_REC)."""
        data = bytearray(self.load())
        data[offset] = value
        self.save(bytes(data))


def nvm_sync_roundtrip(
    port: serial.Serial, op: int, chunk: bytes | None = None
) -> tuple[int, int, bytes]:
    """Send one NVM_SYNC frame, return (status, valid_mask, data_echo 28B)."""
    request = bytes((REQUEST_NVM_SYNC, op))
    if op in (NVM_SUB_PUSH_LO, NVM_SUB_PUSH_HI):
        if chunk is None or len(chunk) != NVM_CHUNK_LEN:
            raise RuntimeError("nvm_sync: PUSH requires 32B chunk")
        crc = crc16_ccitt(chunk)
        request += chunk + bytes((crc & 0xFF, crc >> 8))
    write_paced(port, request)
    response = read_exact(port, RESPONSE_SIZE)
    if response[0] != RESPONSE or response[1] != 0:
        raise RuntimeError(
            f"nvm_sync: marker=0x{response[0]:02x} status={response[1]}"
        )
    return response[18], response[19], bytes(response[20:48])


def nvm_push_state(port: serial.Serial, state: bytes) -> None:
    """Push the 64B STATE_REC back into the firmware volatile NVM slot in two halves."""
    if len(state) != NVM_STATE_LEN:
        raise RuntimeError(f"nvm_push_state: length {len(state)} != {NVM_STATE_LEN}")
    status, mask, _ = nvm_sync_roundtrip(port, NVM_SUB_PUSH_LO, state[:NVM_CHUNK_LEN])
    if status != 0:
        raise RuntimeError(f"nvm_push_state: PUSH_LO status={status}")
    status, mask, _ = nvm_sync_roundtrip(port, NVM_SUB_PUSH_HI, state[NVM_CHUNK_LEN:])
    if status != 0 or mask != 0x3:
        raise RuntimeError(f"nvm_push_state: PUSH_HI status={status} mask={mask}")


def nvm_read_state_lo28(port: serial.Serial) -> bytes:
    """Read back the first 28B of the firmware NVM lo half (for consistency checks)."""
    status, mask, echo = nvm_sync_roundtrip(port, NVM_SUB_READ)
    if status != 0 or mask != 0x3:
        raise RuntimeError(f"nvm_read: status={status} mask={mask}")
    return echo


def run_nvm_sync_case(port: serial.Serial) -> None:
    """Real board: push STATE_REC back from the persistent-domain file, then read back the first 28B of the lo half to verify consistency."""
    store = NvmStore()
    state = store.load()
    nvm_push_state(port, state)
    echo = nvm_read_state_lo28(port)
    if echo != state[:28]:
        raise RuntimeError(
            f"nvm-sync: read-back mismatch echo={echo.hex()} expected={state[:28].hex()}"
        )
    print(f"PASS: nvm-sync push+read lo28 consistent file={store.path}")


